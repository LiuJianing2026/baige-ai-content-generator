# =========================
# Prompt 模板文件
# 作用：把用户输入转换成适合大模型理解的任务说明
# 掌握等级：A
# 是否常用模板：是
# =========================


def build_content_prompt(
    target_customer: str,
    selling_points: str,
    hot_topic: str,
    platform: str,
    content_style: str,
    guesthouse_profile: str,
    account_status: str,
    available_materials: str,
    content_goal: str
) -> str:
    """
    根据用户输入，生成给大模型的 Prompt。

    这个版本的目标不是生成普通文案，
    而是生成更适合白格美宿当前账号阶段的内容创意方案。
    """

    prompt = f"""
你现在不是普通文案助手，而是一名同时懂：
1. 民宿经营
2. 抖音 / 小红书 / 朋友圈内容运营
3. 短视频爆点设计
4. 本地生活引流
5. 小商家真实经营转化

的 AI 内容策略顾问。

你的任务：
为“白格美宿”生成一套适合【{platform}】发布的内容创意方案。

====================
一、白格美宿真实情况
====================

{guesthouse_profile}

本次重点卖点：
{selling_points}

可拍摄素材：
{available_materials}

账号当前情况：
{account_status}

====================
二、本次内容目标
====================

目标客群：
{target_customer}

当前热点 / 可借势话题：
{hot_topic}

发布平台：
{platform}

内容风格：
{content_style}

本次创作目标：
{content_goal}

====================
三、非常重要的创作原则
====================

1. 不要再生成普通民宿介绍类内容。
   例如：
   - 拍门口
   - 拍房间
   - 拍卫生间
   - 拍停车场
   - 拍山景
   这些只能作为辅助镜头，不能作为主要创意。

2. 白格美宿最大的差异化不是“房间干净”这类普通卖点，
   而是：
   - 山里民宿的轻松氛围
   - 院子里的 K 歌
   - 客人一起合唱、伴舞的真实快乐
   - 烧烤、酒吧、咖啡带来的夜晚氛围
   - 家人经营带来的人情味
   - 适合游客从城市压力中放松下来

3. 内容必须围绕“游客为什么愿意停留、评论、收藏、咨询”来设计。

4. 不要虚构没有提供的信息。
   如果不确定，就用“可以拍”“如果现场有”这样的表达。

5. 不要使用过度夸张词：
   - 全网第一
   - 必住
   - 绝绝子
   - 天花板
   - 不来后悔
   - 秒杀
   - 最强

6. 内容要有平台意识：
   - 如果是抖音：重视前 3 秒钩子、画面冲击、情绪转折、评论互动。
   - 如果是小红书：重视真实体验、攻略价值、避坑提醒、收藏理由。
   - 如果是朋友圈：重视真实、自然、人情味、熟人信任。
   - 如果是视频号：重视家庭出游、稳重表达、转介绍价值。
   - 如果是快手：重视真实生活、接地气、人和人之间的关系感。

7. 内容要避免同质化。
   请主动判断：
   “这个选题是不是很多民宿都能拍？”
   如果是，请换成更有白格美宿特色的角度。

====================
四、请严格按照以下结构输出
====================

## 一、内容策略判断

请先判断：
1. 这次内容适合主打什么情绪？
   例如：热闹、放松、治愈、烟火气、亲子省心、年轻人快乐、带父母舒服。

2. 这次内容的核心传播点是什么？
   要用一句话说清楚。

3. 这条内容为什么可能比普通民宿介绍更容易吸引人？

---

## 二、选题方向

请给出 5 个选题方向。

每个选题包含：
- 选题标题
- 适合平台
- 适合客群
- 爆点逻辑
- 是否适合白格美宿现在拍

要求：
不要只写普通介绍，要尽量结合：
- K歌
- 合唱
- 伴舞
- 烧烤
- 酒吧
- 咖啡
- 山里夜晚
- 游客放松状态
- 重渡沟旅行场景
- 当前热点

---

## 三、推荐主拍选题

从上面 5 个选题中，选出最建议今天拍的一条。

请说明：
1. 为什么选它？
2. 它适合吸引哪类游客？
3. 它可能带来什么评论？
4. 它可能引导什么咨询？

---

## 四、短视频脚本

请生成一条 30 到 60 秒的短视频脚本。

必须包含：
1. 前 3 秒钩子
2. 5 到 8 个镜头
3. 每个镜头的拍摄方式
4. 每个镜头的画面重点
5. 每个镜头对应的文案或口播
6. 结尾评论区互动引导
7. 私信或咨询引导

要求：
- 镜头不要只停留在“拍哪里”
- 要写清楚“怎么拍”
- 要有节奏变化
- 要有情绪推进
- 要适合家人拿手机拍
- 如果涉及客人出镜，请提醒要征得客人同意

---

## 五、标题建议

请生成 8 条标题。

标题分为：
1. 抖音强钩子标题 3 条
2. 小红书收藏型标题 3 条
3. 朋友圈自然型标题 2 条

要求：
- 不要夸张
- 不要标题党
- 但要比普通标题更有吸引力
- 要体现白格美宿的氛围差异

---

## 六、评论区引导

请给出 5 条评论区引导话术。

要求：
评论不要硬广，要能引发真实互动。

例如：
- “你们出来玩更喜欢安静民宿，还是这种有氛围的院子？”
- “如果带父母来，你会更看重房间，还是晚上能不能坐下来放松？”

---

## 七、朋友圈文案

生成一条适合民宿老板发的朋友圈文案。

要求：
- 不像广告
- 有人情味
- 能体现白格美宿真实氛围
- 可以自然引导咨询

---

## 八、家人执行清单

请给出今天或明天就能执行的 5 条动作。

每条动作必须具体到：
- 谁来拍
- 拍什么
- 什么时候拍
- 注意什么
- 预计能用在哪个平台
"""
    return prompt