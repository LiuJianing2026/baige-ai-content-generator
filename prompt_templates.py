# =========================
# Prompt 模板文件
# 作用：把用户输入转换成适合大模型理解的任务说明
# 掌握等级：A
# 是否常用模板：是
# =========================


def build_content_prompt(
    target_customer: str,
    selling_points: str,
    hot_topic: str,
    platform: str
) -> str:
    """
    根据用户输入，生成给大模型的 Prompt。

    输入：
    - target_customer：目标客群
    - selling_points：民宿卖点
    - hot_topic：当前热点
    - platform：发布平台

    输出：
    - 一段完整的 Prompt 文本
    """

    prompt = f"""
你现在是一名懂民宿经营、短视频内容运营和小红书种草文案的 AI 经营助理。

你的任务：
为“白格美宿”生成一套适合发布到【{platform}】的内容方案。

白格美宿背景：
- 白格美宿位于河南省洛阳市栾川县重渡沟附近。
- 目标是吸引真实游客咨询和入住。
- 内容必须真实、自然、可执行。
- 不要写得像夸张广告。
- 不要虚构没有提供的信息。
- 重点解决游客的真实顾虑，比如停车、卫生、带孩子、带父母、距离景区、避暑、吃饭方便等。

用户输入：
- 目标客群：{target_customer}
- 民宿卖点：{selling_points}
- 当前热点：{hot_topic}
- 发布平台：{platform}

请严格按照下面结构输出：

## 一、标题建议

请生成 5 条标题。
要求：
- 适合【{platform}】发布
- 口语化
- 有吸引力但不夸张
- 尽量突出游客真实关心的问题

## 二、短视频脚本

请生成 1 条短视频脚本。
必须包含：
1. 开头 3 秒怎么说
2. 中间展示哪些内容
3. 结尾如何引导咨询

要求：
- 家人拿手机就能照着拍
- 不要复杂运镜
- 不要专业团队才能完成的拍法

## 三、镜头清单

请列出 6 到 8 个镜头。
每个镜头都要说明：
- 拍什么
- 为什么拍
- 这个镜头解决游客什么顾虑

## 四、朋友圈文案

请生成 1 条朋友圈文案。
要求：
- 像真实民宿老板发的
- 自然、有温度
- 不要太营销
- 适合配图片或短视频

## 五、家人执行提醒

请补充 3 条执行建议。
要求：
- 具体
- 简单
- 今天或明天就能做
"""
    return prompt