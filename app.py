import streamlit as st


# =========================
# 页面基础配置
# =========================
st.set_page_config(
    page_title="白格美宿内容方案生成器",
    page_icon="🏡",
    layout="centered"
)


# =========================
# 页面标题
# =========================
st.title("🏡 白格美宿内容方案生成器 v0.1")

st.write(
    "输入目标客群、民宿卖点、当前热点和发布平台，"
    "系统会生成一套适合白格美宿发布的内容方案。"
)

st.divider()


# ---------------------------------------------------------------------------
# 【学习标注】表单输入（text_input / text_area / selectbox）
# 业务作用：把经营信息结构化，供后续生成（或将来接 AI）使用。
# 输入：用户在网页上的键盘输入；发布平台为下拉单选。
# 处理：Streamlit 将控件值绑定到 Python 变量。
# 输出：target_customer、selling_points、hot_topic、platform 四个变量。
# 掌握等级：A（控件、变量、placeholder 要会写会改）。
# 常用模板：是。
# 手写要求：必须能手写；加字段即多加控件并向下游多传参。
# 经营场景：如「亲子家庭 + 停车方便离重渡沟近 + 暑假避暑 + 小红书」。
# 复用：字段改成「菜品、套餐、活动、渠道」等即可换行业。
# 备注：platform 已收集；mock 函数内暂未拼进文案，预留接 AI 时分平台模板。
# ---------------------------------------------------------------------------
st.subheader("第一步：填写内容需求")

target_customer = st.text_input(
    "目标客群",
    placeholder="例如：亲子家庭、情侣游客、带父母出游、河南周边自驾游客"
)

selling_points = st.text_area(
    "民宿卖点",
    placeholder="例如：停车方便，房间干净，离重渡沟景区近，适合带孩子避暑"
)

hot_topic = st.text_input(
    "当前热点",
    placeholder="例如：暑假避暑、河南周边游、带娃出游、重渡沟旅游"
)

platform = st.selectbox(
    "发布平台",
    ["抖音", "小红书", "朋友圈", "视频号"]
)

st.divider()


# ---------------------------------------------------------------------------
# 【学习标注】mock_generate_content — 模拟生成（不接 API）
# 业务作用：用假数据跑通「输入 → 一篇方案」形态；文案嵌入重渡沟/白格语境。
# 输入：target_customer、selling_points、hot_topic、platform（platform 当前未参与拼接）。
# 处理：f-string 把用户填写内容嵌入固定 Markdown 大纲。
# 输出：一段 Markdown 字符串。
# 掌握等级：A（函数、参数、return、拼接）；B（大纲结构、话术要会改）。
# 常用模板：是（「函数收上下文 → 返回长文本」；接 AI 时常改为调 API）。
# 手写要求：逻辑骨架能手写；具体句子可复制后迭代。
# 经营场景：强调停车、卫生、到景区、旺季订房等决策与口碑敏感点。
# 复用：四段大纲可换成海报/私域/团购等，仍复用同一套入参。
# ---------------------------------------------------------------------------
def mock_generate_content(target_customer, selling_points, hot_topic, platform):
    result = f"""
## 一、标题建议

1. {hot_topic}别只看攻略，来重渡沟住得舒服也很重要
2. 适合{target_customer}的重渡沟民宿，省心比打卡更重要
3. 来重渡沟避暑，这几个住宿细节一定要提前看
4. {selling_points}，这样的民宿更适合一家人出游
5. 河南周边游想少折腾，可以看看白格美宿

---

## 二、短视频脚本

### 开头 3 秒

“最近想来重渡沟玩的朋友，尤其是{target_customer}，住宿一定要提前看好。”

### 中间内容

先拍白格美宿门口和周边环境，再展示停车位置、房间卫生、床品情况和到景区的便利程度。  
重点突出：{selling_points}。

### 结尾引导

“准备来重渡沟的朋友，可以提前问问房型和日期，旺季建议早点安排。”

---

## 三、镜头清单

1. 民宿门口全景：让游客知道到店第一眼是什么样。
2. 停车位置：突出自驾游客关心的停车问题。
3. 房间床品：展示干净、整洁、舒适。
4. 卫生间：增加游客对卫生条件的信任。
5. 周边山景：突出重渡沟避暑和自然环境。
6. 家常饭菜：体现民宿生活感和烟火气。
7. 到景区路线：让游客感受到位置方便。

---

## 四、朋友圈文案

最近来重渡沟玩的朋友越来越多，很多客人最关心的其实不是玩多少景点，  
而是住得舒不舒服、停车方不方便、带家人会不会累。

白格美宿这边适合{target_customer}，{selling_points}。  
准备{hot_topic}的朋友，可以提前看看房型和日期。

山里晚上比较凉快，适合慢慢住两天。
"""
    return result


# ---------------------------------------------------------------------------
# 【学习标注】生成按钮、校验、展示与下载
# 业务作用：防漏填；生成后即时阅读；下载 .md 便于发给同事或导入笔记。
# 输入：用户点击「生成内容方案」；以及表单各字段当前值。
# 处理：三字段为空则 warning；否则 success、调用 mock、markdown 渲染、
#       download_button 提供下载。
# 输出：提示信息、正文方案、文件「白格美宿内容方案.md」。
# 掌握等级：A（if、按钮、布尔判断）；B（下载 mime、file_name、提示文案）。
# 常用模板：是（提交 → 校验 → 展示 → 下载）。
# 手写要求：分支与按钮能手写；下载参数要能改。
# 经营场景：避免「客群/卖点/热点」为空仍生成不可用方案。
# 复用：把校验条件改成你业务里的必填项即可。
# ---------------------------------------------------------------------------
st.subheader("第二步：生成内容方案")

generate_button = st.button("生成内容方案")

if generate_button:
    if not target_customer or not selling_points or not hot_topic:
        st.warning("请先填写目标客群、民宿卖点和当前热点。")
    else:
        st.success("内容方案已生成，下面是模拟结果。")

        generated_content = mock_generate_content(
            target_customer=target_customer,
            selling_points=selling_points,
            hot_topic=hot_topic,
            platform=platform
        )

        st.markdown(generated_content)

        st.download_button(
            label="下载内容方案",
            data=generated_content,
            file_name="白格美宿内容方案.md",
            mime="text/markdown"
        )


# ---------------------------------------------------------------------------
# 【学习标注】页脚说明（st.caption）
# 业务作用：管理预期——v0.1 原型、模拟结果、未接 AI，减少误解。
# 输入：无。
# 处理：渲染小号说明文字。
# 输出：页面底部灰色 caption。
# 掌握等级：B。
# 常用模板：是。
# 手写要求：发版时更新版本与说明句。
# 经营场景：对内培训工具时说明「为何与线上 ChatGPT 体验不同」。
# 复用：随项目成熟度改写一句版本说明即可。
# ---------------------------------------------------------------------------
st.divider()

st.caption(
    "当前版本：v0.1 页面原型。今天只验证输入和输出流程，暂不接入 AI API。"
)
